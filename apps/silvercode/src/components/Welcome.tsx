/**
 * Resolved at module-load: absolute path to silver-code.png. The PNG
 * ships next to apps/silvercode/package.json, so from this file
 * (apps/silvercode/src/components/Welcome.tsx) it lives two dirs up.
 *
 * If the file is missing, we throw immediately so the failure is loud
 * (the alternative — silently falling back to text — masked the real
 * "I don't see the logo" symptom).
 */
const SILVER_CODE_PNG_PATH: string = (() => {
  const dir = import.meta.dirname ?? __dirname
  if (!dir) throw new Error("silvercode: unable to resolve module dir for silver-code.png lookup")
  const candidate = resolvePath(dir, "..", "..", "silver-code.png")
  if (!existsSync(candidate)) {
    throw new Error(`silvercode: silver-code.png not found at ${candidate}`)
  }
  return candidate
})()

/**
 * PNG dimensions read from the file header. We use the actual image's
 * aspect ratio rather than hardcoding any 3:2 / 3:1 / etc. constant —
 * if the asset gets re-cropped (which it has been) the displayed banner
 * automatically tracks the new aspect.
 *
 * PNG header layout: bytes 0-7 = magic, byte 8-11 = IHDR chunk length,
 * 12-15 = "IHDR", 16-19 = width (big-endian u32), 20-23 = height.
 */
const SILVER_CODE_PNG_DIMENSIONS: { readonly width: number; readonly height: number } = (() => {
  const head = readFileSync(SILVER_CODE_PNG_PATH).subarray(0, 24)
  const sig = head.subarray(0, 8).toString("hex")
  if (sig !== "89504e470d0a1a0a") {
    throw new Error(`silvercode: silver-code.png is not a valid PNG (sig=${sig})`)
  }
  const width = head.readUInt32BE(16)
  const height = head.readUInt32BE(20)
  if (!Number.isFinite(width) || !Number.isFinite(height) || width <= 0 || height <= 0) {
    throw new Error(`silvercode: silver-code.png has invalid IHDR dimensions ${width}x${height}`)
  }
  return { width, height }
})()

/**
 * Min container width for each tier (cols). The ladder steps:
 *   ≥ 56 + Kitty graphics → Image (silver-code.png via Kitty/Sixel) — wide-terminal default
 *   ≥ 56 → Shaded (52 cols + breathing room) — text-only fallback
 *   ≥ 44 → Big (~40 cols)
 *   ≥ 36 → standard (33 cols)
 *   ≥ 28 → small (26 cols)
 *    < 28 → stacked-text fallback
 */
const SHADED_MIN_COLS = 56
const BIG_MIN_COLS = 44
const STANDARD_MIN_COLS = 36
const SMALL_MIN_COLS = 28

type BannerTier = "image" | "shaded" | "big" | "standard" | "small" | "stacked"

/**
 * Detect Kitty graphics protocol support once at module load. Test
 * envs (`NODE_ENV=test`, vitest) skip the image tier because termless
 * / createRenderer can't paint Kitty escapes — letting tests fall
 * through to the shaded text tier keeps assertion signatures stable.
 *
 * Detection errors are NOT swallowed — if `isKittyGraphicsSupported()`
 * throws, the exception propagates so the failure is visible.
 */
const KITTY_SUPPORTED: boolean = (() => {
  if (process.env.NODE_ENV === "test" || process.env.VITEST) return false
  return isKittyGraphicsSupported()
})()

function chooseBannerTier(width: number): BannerTier {
  // Image tier requires Kitty graphics support and enough room. Falls
  // through to the shaded text tier when Kitty isn't available; the
  // PNG path is mandatory at module load (throws if missing) so it's
  // not part of the runtime gate.
  if (width >= SHADED_MIN_COLS && KITTY_SUPPORTED) return "image"
  if (width >= SHADED_MIN_COLS) return "shaded"
  if (width >= BIG_MIN_COLS) return "big"
  if (width >= STANDARD_MIN_COLS) return "standard"
  if (width >= SMALL_MIN_COLS) return "small"
  return "stacked"
}

/**
 * Render a multi-line figlet block as one `<Text>` per row. Each row is its
 * own `<Text wrap={false}>` so a narrow container can't wrap the ASCII art
 * mid-glyph (the tier picker should already have chosen a smaller block, but
 * `wrap={false}` is belt-and-suspenders against alignment damage).
 */
function FigletBlock({ rows, color }: { rows: ReadonlyArray<string>; color: string }): React.ReactElement {
  return (
    <Box flexDirection="column" alignItems="center">
      {rows.map((row, i) => (
        <Text key={i} bold color={color} wrap={false}>
          {row}
        </Text>
      ))}
    </Box>
  )
}


/**
 * Silver Code banner — block letters + agent label.
 *
 * Two-color split: SILVER → `$primary` (cool brand mark), CODE → `$accent`
 * (warm contrast). Both are silvery semantic tokens that resolve sensibly
 * across 84+ themes. The Big primary tier is the wordmark — when the user
 * opens silvercode on a wide terminal the banner occupies roughly the
 * upper third of the screen (~9 rows × 2 + gap + agent label ≈ 20 lines),
 * big enough to read as a product mark, not a footnote.
 *
 * Tier-pick based on `availableWidth` so narrow panes degrade gracefully:
 *   width >= 56 → Shaded blocks (52-col, 7 rows, ░░▒▒▓▓█ gradient) ← primary
 *   width >= 44 → Big figlet (40-col blocks × 6 rows)
 *   width >= 36 → standard figlet (33-col blocks × 5 rows)
 *   width >= 28 → small figlet (26-col blocks × 4 rows)
 *   otherwise   → simple stacked text "SILVER" / "CODE"
 *
 * Bead: km-cr94.
 */
export function SilverCodeBanner({
  agentLabel,
  availableWidth,
}: {
  agentLabel?: string
  availableWidth: number
}): React.ReactElement {
  const tier = chooseBannerTier(availableWidth)

  let block: React.ReactElement
  if (tier === "image") {
    // Kitty graphics path — derive the displayed cell-grid dimensions
    // from the PNG's actual pixel dimensions (read at module load).
    // Terminal cells are about twice as tall as they are wide, so for
    // a faithful display the cell-grid aspect must be the PNG's pixel
    // aspect divided by that cell-shape factor — no per-image
    // hardcoded ratios.
    const CELL_HEIGHT_TO_WIDTH = 2
    const { width: pngW, height: pngH } = SILVER_CODE_PNG_DIMENSIONS
    const imgW = Math.max(20, availableWidth - 4)
    const imgH = Math.max(5, Math.round((imgW * pngH) / (pngW * CELL_HEIGHT_TO_WIDTH)))
    block = (
      <Box flexDirection="column" alignItems="center">
        <Image src={SILVER_CODE_PNG_PATH} width={imgW} height={imgH} fallback="SILVER CODE" />
      </Box>
    )
  } else if (tier === "shaded") {
    // Positive-space gradient — letters are filled with shade chars
    // (░ ░ ▒ ▒ ▓ ▓ █ across the 7 rows of each wordmark), so the text
    // itself fades top-light to bottom-dark. SILVER and CODE are
    // stacked with one blank row between them.
    block = (
      <Box flexDirection="column" alignItems="center" gap={1}>
        <FigletBlock rows={SILVER_SHADED} color="$primary" />
        <FigletBlock rows={CODE_SHADED} color="$accent" />
      </Box>
    )
  } else if (tier === "big") {
    block = (
      <Box flexDirection="column" alignItems="center" gap={1}>
        <FigletBlock rows={SILVER_BIG} color="$primary" />
        <FigletBlock rows={CODE_BIG} color="$accent" />
      </Box>
    )
  } else if (tier === "standard") {
    block = (
      <Box flexDirection="column" alignItems="center" gap={1}>
        <FigletBlock rows={SILVER_STANDARD} color="$primary" />
        <FigletBlock rows={CODE_STANDARD} color="$accent" />
      </Box>
    )
  } else if (tier === "small") {
    block = (
      <Box flexDirection="column" alignItems="center" gap={1}>
        <FigletBlock rows={SILVER_SMALL} color="$primary" />
        <FigletBlock rows={CODE_SMALL} color="$accent" />
      </Box>
    )
  } else {
    block = (
      <Box flexDirection="column" alignItems="center">
        <Text bold color="$primary">
          SILVER
        </Text>
        <Text bold color="$accent">
          CODE
        </Text>
      </Box>
    )
  }

  return (
    <Box flexDirection="column" alignItems="center" gap={1}>
      {block}
      {agentLabel ? <Small color="$muted">{agentLabel}</Small> : null}
    </Box>
  )
}

/**
 * Width-aware wrapper. `useBoxRect` reads the host node's measured width and
 * triggers a re-render when it changes. On the first paint width is 0; we
 * defer rendering the inner banner until measurement returns a positive
 * width — this avoids the layout jump where a fallback-width banner paints
 * once, then re-paints at the actual width on the second pass.
 *
 * The OUTER Box always renders (it's the node being measured); only the
 * SilverCodeBanner inside is gated on width > 0.
 */
export function MeasuredBanner({ agentLabel }: { agentLabel?: string }): React.ReactElement {
  const { width } = useBoxRect()
  // `alignSelf="stretch"` makes this Box fill the parent's cross-axis so
  // `useBoxRect` reads the FULL pane width — needed by the shaded tier
  // for full-width row padding. Without stretch the Box shrinks to the
  // banner's natural content width and the shaded gradient only spans
  // the centered ~52 cols instead of the whole pane.
  return (
    <Box flexDirection="column" alignSelf="stretch" alignItems="center">
      {width > 0 ? <SilverCodeBanner agentLabel={agentLabel} availableWidth={width} /> : null}
    </Box>
  )
}

/** Truncate UUID-style ids to a readable prefix for the loading line. */
export function shortenSessionId(id: string | undefined): string {
  if (!id) return ""
  if (id.length <= 24) return id
  return id.slice(0, 8) + "…"
}

/**
 * Empty-state screen — banner + the App-level `SessionPromptComposer`,
 * both centered. The composer is THE SAME element rendered at the bottom
 * of the layout in chat state — App threads it down as `composerSlot`
 * so we keep one component and one set of state. Only its parent slot
 * differs (centered here vs bottom-anchored in chat state).
 *
 * Visually: banner + agent label, followed by either the composer
 * (fresh session) or a quiet "Loading session <id>…" line (resume),
 * stacked and centered both axes in the available pane height. Bead:
 * km-cr94.
 */
export function Welcome(props: {
  handle: SessionHandle
  /** Canonical agent id — drives the `<agent label>` muted line below the banner. */
  agent?: string
  /** Session status from the store. Currently informational only — the
   *  fresh/loading split is driven by `handle.resumeId`, not status. */
  status?: string
  /**
   * The App-level `SessionPromptComposer` element, threaded through
   * PaneGrid → SessionCard so the composer here and the (suppressed)
   * bottom-anchored render reference the same controlled component +
   * App-owned state. Width-capped here for visual centering; placement
   * is the only difference from the chat-state render. When omitted
   * (component-level fixture tests), the centered slot is empty and
   * the test asserts banner-only chrome.
   */
  composerSlot?: React.ReactNode
}): React.ReactElement {
  const agentLabel = props.agent ? AGENT_LABELS[props.agent] : undefined
  const resumeId = props.handle.resumeId
  const isLoading = typeof resumeId === "string" && resumeId.length > 0

  return (
    // Center the brand mark on both axes. `flexGrow={1}` claims the full
    // pane height; `justifyContent="center"` + `alignItems="center"` pin
    // contents to the visual center. `gap={1}` sets breathing room
    // between the banner and the composer / loading line.
    <Box flexDirection="column" flexGrow={1} alignItems="center" justifyContent="center" gap={1} paddingX={2}>
      <MeasuredBanner agentLabel={agentLabel} />

      {isLoading ? (
        <Muted>Loading session {shortenSessionId(resumeId)}…</Muted>
      ) : props.composerSlot ? (
        <Box flexDirection="column" flexShrink={0} width={80} maxWidth={80} minWidth={0}>
          {props.composerSlot}
        </Box>
      ) : null}
    </Box>
  )
}
