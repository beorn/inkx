/*
 * SILVER / CODE figlet block letters (pre-generated, NOT runtime-rendered).
 *
 * Generated with `figlet` so the per-row character alignment is correct
 * (LLMs reliably misalign hand-rolled multi-line ASCII art — see memory:
 * `feedback-no-box-diagrams`). Pasted as string-literal constants so the
 * app has no runtime dep on figlet and the lines are immutable.
 *
 * To regenerate (output is deterministic for the given font + word):
 *   figlet -f Big      "SILVER"
 *   figlet -f Big      "CODE"
 *   figlet -f standard "SILVER"
 *   figlet -f standard "CODE"
 *   figlet -f small    "SILVER"
 *   figlet -f small    "CODE"
 *
 * Width / height measurements (load-bearing for the tier picker):
 *   Big      SILVER: 40 cols × 6 rows
 *   Big      CODE:   28 cols × 6 rows
 *   standard SILVER: 33 cols × 5 rows
 *   standard CODE:   24 cols × 5 rows
 *   small    SILVER: 26 cols × 4 rows
 *   small    CODE:   20 cols × 4 rows
 *
 * Bead: km-cr94.
 */

/*
 * Shaded tier — POSITIVE-SPACE, per-row gradient.
 *
 * The letters themselves are filled with shade chars (the gradient is in
 * the text, not the background). 7 rows per wordmark, each row uses a
 * single shade char in monotonic ░ ░ ▒ ▒ ▓ ▓ █ progression — so the
 * letter strokes fade from soft highlight at top to solid block at
 * bottom (classic old-Apple chrome). SILVER and CODE are stacked with a
 * blank row between them.
 *
 * Width: 52 cols (SILVER), 38 cols (CODE).
 * Height: 7 rows each text block + 1 blank separator = 15 rows total.
 *
 * Stored in apps/silvercode/silver-code.txt so the generated wordmark is
 * inspectable as an asset, like silver-code.png.
 *
 * Regenerate the positive-space art:
 *   figlet -f banner3 -w 200 SILVER | awk '
 *     NR==1||NR==2{gsub(/#/,"░");print}
 *     NR==3||NR==4{gsub(/#/,"▒");print}
 *     NR==5||NR==6{gsub(/#/,"▓");print}
 *     NR==7        {gsub(/#/,"█");print}'
 */
const SILVER_CODE_TEXT_PATH: string = (() => {
  const dir = import.meta.dirname ?? __dirname
  if (!dir) throw new Error("silvercode: unable to resolve module dir for silver-code.txt lookup")
  return resolvePath(dir, "..", "..", "silver-code.txt")
})()

function readTextLogoBlocks(path: string): readonly [ReadonlyArray<string>, ReadonlyArray<string>] {
  const blocks = readFileSync(path, "utf8")
    .trimEnd()
    .split(/\n\n/)
    .map((block) => block.split("\n"))
  if (blocks.length !== 2 || !blocks[0] || !blocks[1]) {
    throw new Error(`silvercode: silver-code.txt must contain SILVER and CODE blocks separated by one blank line`)
  }
  return [blocks[0], blocks[1]]
}

